"""Build bundled station/line geometry from saved TfL Route/Sequence/all responses.
Usage: python3 scripts/build-tfl-network.py /tmp/tubecast-tfl
Routes at runtime come from Journey Planner, never this geometry.
"""
import json,sys,re,datetime
from pathlib import Path
root=Path(sys.argv[1]);lines={f.stem:json.loads(f.read_text()) for f in sorted(root.glob('*.json'))}
stations={};paths={}
for line,d in lines.items():
 for st in d['stations']:
  key=st.get('icsId') or st['id'];s=stations.setdefault(key,{'name':re.sub(r' (Underground|Rail|DLR|Elizabeth line) Station$','',st['name']),'lat':st['lat'],'lon':st['lon'],'icsId':st.get('icsId'),'naptanIds':[],'lines':[]})
  if st['id'] not in s['naptanIds']:s['naptanIds'].append(st['id'])
  if line not in s['lines']:s['lines'].append(line)
 edges=set();points={};adj={}
 for raw in d['lineStrings']:
  for path in json.loads(raw):
   for a,b in zip(path,path[1:]):
    ka=tuple(a);kb=tuple(b)
    if ka==kb:continue
    edge=tuple(sorted((ka,kb)))
    if edge in edges:continue
    edges.add(edge);adj.setdefault(ka,set()).add(kb);adj.setdefault(kb,set()).add(ka)
 unused=set(edges);chains=[]
 def walk(a,b):
  chain=[a,b];unused.discard(tuple(sorted((a,b))))
  while len(adj[b])==2:
   c=next((v for v in adj[b] if v!=a),None)
   if c is None or tuple(sorted((b,c))) not in unused:break
   unused.remove(tuple(sorted((b,c))));chain.append(c);a,b=b,c
  chains.append(chain)
 for a in adj:
  if len(adj[a])!=2:
   for b in adj[a]:
    if tuple(sorted((a,b))) in unused:walk(a,b)
 while unused:walk(*next(iter(unused)))
 paths[line]=chains
names={}
for s in stations.values():
 n=s['name'];n={"King's Cross St. Pancras":"King's Cross","King's Cross & St Pancras International":"King's Cross","Heathrow Terminals 2 & 3":"Heathrow Terminals 2 & 3"}.get(n,n)
 if n in names:n+=' ('+'/'.join(s['lines'])+')'
 names[n]=1;s['name']=n;s['id']=re.sub(r'[^a-z0-9]+','-',n.lower().replace("'",'').replace('&','and')).strip('-')
d={'source':'Transport for London Unified API · /Line/{id}/Route/Sequence/all','retrievedAt':datetime.datetime.now(datetime.timezone.utc).isoformat(),'stations':list(stations.values()),'paths':paths}
Path('assets/tfl-network.json').write_text(json.dumps(d,separators=(',',':')))
Path('assets/tfl-network.js').write_text('/* Official TfL network snapshot. Generated by scripts/build-tfl-network.py. */\nwindow.TFL_NETWORK='+json.dumps(d,separators=(',',':'))+';\n')
print(len(d['stations']),'stations',sum(len(v) for v in paths.values()),'line chains')
