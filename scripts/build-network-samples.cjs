/* Offline geometry cache. Run after editing assets/network.js:
   node scripts/build-network-samples.cjs
   No packages needed. Curves are flattened to 0.002 map-pixel tolerance. */
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..'),scope={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'assets/network.js'),'utf8'),scope);
if(process.argv.includes('--extended')){scope.NET=scope.window.NET;vm.runInNewContext(fs.readFileSync(path.join(root,'assets/schematic-extension.js'),'utf8'),scope);scope.SCHEMATIC_EXTENSION=scope.window.SCHEMATIC_EXTENSION;vm.runInNewContext(fs.readFileSync(path.join(root,'js/schematic-map.js'),'utf8'),scope);}
const N=scope.window.NET,S=1440/656,step=7;
const source=JSON.stringify([N.central,N.lines]);
let hash=2166136261;for(let i=0;i<source.length;i++)hash=Math.imul(hash^source.charCodeAt(i),16777619);
function flatten(d){
 const tokens=d.match(/[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:e[-+]?\d+)?/gi),pts=[];
 let i=0,cmd,x=0,y=0;
 const number=()=>{const v=Number(tokens[i++]);if(!Number.isFinite(v))throw Error('Invalid path '+d);return Math.fround(v);};
 function curve(a,b,c,z,depth=0){
  const dist=(p,q)=>Math.hypot(p[0]-q[0],p[1]-q[1]);
  if(depth>=16||dist(a,b)+dist(b,c)+dist(c,z)-dist(a,z)<.002){pts.push(z);return;}
  const mid=(p,q)=>[(p[0]+q[0])/2,(p[1]+q[1])/2];
  const ab=mid(a,b),bc=mid(b,c),cz=mid(c,z),abc=mid(ab,bc),bcz=mid(bc,cz),m=mid(abc,bcz);
  curve(a,ab,abc,m,depth+1);curve(m,bcz,cz,z,depth+1);
 }
 while(i<tokens.length){
  if(/[A-Za-z]/.test(tokens[i]))cmd=tokens[i++];
  if(cmd==='M'){if(pts.length)throw Error('Multiple subpaths need separate fragments');x=number();y=number();pts.push([x,y]);cmd='L';}
  else if(cmd==='L'){x=number();y=number();pts.push([x,y]);}
  else if(cmd==='H'){x=number();pts.push([x,y]);}
  else if(cmd==='V'){y=number();pts.push([x,y]);}
  else if(cmd==='C'){const b=[number(),number()],c=[number(),number()],z=[number(),number()];curve([x,y],b,c,z);[x,y]=z;}
  else throw Error('Unsupported SVG command '+cmd);
 }
 const lengths=[0];for(let j=1;j<pts.length;j++)lengths.push(lengths[j-1]+Math.hypot(pts[j][0]-pts[j-1][0],pts[j][1]-pts[j-1][1]));
 const L=lengths.at(-1),n=Math.max(1,Math.ceil(L*S/step)),out=[];let j=1;
 for(let k=0;k<=n;k++){const target=L*k/n;while(j<lengths.length-1&&lengths[j]<target)j++;const f=(target-lengths[j-1])/(lengths[j]-lengths[j-1]||1);out.push(+((pts[j-1][0]+(pts[j][0]-pts[j-1][0])*f).toFixed(4)),+((pts[j-1][1]+(pts[j][1]-pts[j-1][1])*f).toFixed(4)));}
 return out;
}
const lines={};for(const slug of Object.keys(N.colors)){const paths=slug==='central'?N.central.p:N.lines.p.filter(p=>p[0]===slug).map(p=>p[1]);lines[slug]=paths.map(flatten);}
const data={version:1,signature:hash>>>0,step,scale:S,lines};
fs.writeFileSync(path.join(root,process.argv.includes('--extended')?'assets/schematic-samples.js':'assets/network-samples.js'),'/* Generated by scripts/build-network-samples.cjs; do not edit. */\nwindow.NET_SAMPLES='+JSON.stringify(data)+';\n');
console.log('Cached',Object.values(lines).flat().reduce((n,p)=>n+p.length/2,0),'sample points');
